      <li><b>Envenenado</b>: 10 de daño entre cada turno.</li>
      <li><b>Dormido</b>: no puede atacar ni retirarse. Se lanza una moneda entre turnos y, si sale cara, se despierta.</li>
      <li><b>Paralizado</b>: no puede atacar ni retirarse durante su siguiente turno.</li>
