      <p>El juego tiene dos tipos de barajas, que se eligen con las pestañas de la pantalla de inicio. Las barajas <b>Clásicas</b> (1999–2000) se juegan con las reglas de su época; las <b>Modernas</b> (Escarlata y Púrpura), con las reglas actuales. Ambos jugadores usan siempre el mismo tipo. Todo lo anterior (la preparación, robar, una Energía por turno, retirarse una vez, que atacar termina el turno, la Debilidad y la Resistencia) es igual en los dos.</p>
