// Writes versus/shared/decks.ts: the deck catalogue the Versus lobby shows and the server's deck allowlist.
//   node scripts/gen-versus-decks.mjs
// Classic decks come from public/data/decks/index.json .decks (each deck's cards.json gives the name, types and
// featured card ids); modern decks from index.json .modern. The image is the first featured card's small image on
// its public CDN: img/cards/<set>/<n>.webp → https://images.pokemontcg.io/<set>/<n>.png, unless
// public/img/sources.json names another source for the .png (the same mapping scripts/build-web.mjs uses).
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
const out = join(root, 'versus', 'shared', 'decks.ts');
const CDN = 'https://images.pokemontcg.io/';

const sources = JSON.parse(await readFile(join(pub, 'img', 'sources.json'), 'utf8'));
const index = JSON.parse(await readFile(join(pub, 'data', 'decks', 'index.json'), 'utf8'));

function remote(local) {
  if (typeof local !== 'string' || !/^img\/cards\/[\w./-]+\.(?:webp|png)$/.test(local)) throw new Error(`not a card image path: ${local}`);
  const png = local.replace(/\.webp$/, '.png');
  const url = sources[png] || CDN + png.slice('img/cards/'.length);
  if (!/^https:\/\/[a-z0-9.-]+\//.test(url)) throw new Error(`no https source for ${local}: ${url}`);
  return url;
}

const KEY = /^[a-z0-9][a-z0-9-]{0,47}$/;
const TYPES = new Set(['Grass', 'Fire', 'Water', 'Lightning', 'Psychic', 'Fighting', 'Darkness', 'Metal', 'Fairy', 'Dragon', 'Colorless']);
function cleanTypes(types, key) {
  if (!Array.isArray(types) || !types.length) throw new Error(`${key}: no types`);
  for (const t of types) if (!TYPES.has(t)) throw new Error(`${key}: unknown type ${t}`);
  return types;
}
function cleanName(name, key) {
  if (typeof name !== 'string' || !name.trim() || name.length > 60) throw new Error(`${key}: bad name`);
  return name.trim();
}

const decks = {};
for (const key of index.decks) {
  if (!KEY.test(key)) throw new Error(`bad deck key ${key}`);
  const deck = JSON.parse(await readFile(join(pub, 'data', 'decks', key, 'cards.json'), 'utf8'));
  const firstId = deck.featured?.[0];
  const card = deck.cards.find((c) => c.id === firstId) || deck.cards.find((c) => c.kind === 'pokemon') || deck.cards[0];
  if (!card?.img) throw new Error(`${key}: no featured card image`);
  decks[key] = { name: cleanName(deck.name, key), format: 'classic', types: cleanTypes(deck.types, key), img: remote(card.img) };
}
for (const m of index.modern) {
  const key = m.key;
  if (!KEY.test(key)) throw new Error(`bad deck key ${key}`);
  if (decks[key]) throw new Error(`duplicate deck key ${key}`);
  // index.json lists featured cards as [{ id, img }]; older builds used featuredImgs: [path].
  const img = m.featuredImgs?.[0] ?? m.featured?.[0]?.img;
  if (!img) throw new Error(`${key}: no featured card image`);
  decks[key] = { name: cleanName(m.name, key), format: 'modern', types: cleanTypes(m.types, key), img: remote(img) };
}

const classic = Object.keys(decks).filter((k) => decks[k].format === 'classic');
const modern = Object.keys(decks).filter((k) => decks[k].format === 'modern');
const body = Object.entries(decks).map(([k, d]) => `  ${JSON.stringify(k)}: ${JSON.stringify(d)},`).join('\n');
const ts = `// Generated by scripts/gen-versus-decks.mjs from public/data/decks. Do not edit by hand.
export type DeckFormat = "classic" | "modern";
export type DeckInfo = { name: string; format: DeckFormat; types: string[]; img: string };

export const DECKS: Record<string, DeckInfo> = {
${body}
};

export const CLASSIC_DECKS: readonly string[] = ${JSON.stringify(classic)};
export const MODERN_DECKS: readonly string[] = ${JSON.stringify(modern)};
`;
await writeFile(out, ts);
console.log(`versus/shared/decks.ts: ${classic.length} classic + ${modern.length} modern decks`);
