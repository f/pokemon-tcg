export const MESSAGES: Record<Lang, Dict> = { en, tr, ja, es };

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

/** 'tr-TR' → 'tr', 'ja' → 'ja'; anything else → 'en'. */
export function langFromTag(tag: unknown): Lang {
  if (typeof tag !== "string") return "en";
  const base = tag.trim().toLowerCase().split(/[-_]/)[0];
  return isLang(base) ? base : "en";
}

/** The string for `key`, with {name} placeholders filled in. Values are plain text, never HTML. */
export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string>): string {
  const text = MESSAGES[lang]?.[key] ?? en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (Object.prototype.hasOwnProperty.call(vars, name) ? vars[name] : all));
}
